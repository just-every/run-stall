import assert from 'node:assert/strict'
import { startJourney } from './journey-kit.mjs'

// STORE-002: the desk sets up collections, a menu, a synonym and a pin; shoppers browse, search and filter.
let journey, journeyError
try {
 journey = await startJourney({ name: 'discovery', skus: ['TSH-1', 'HAT-1', 'MUG-1', 'BAG-1', 'HOOD-S-BLK', 'HOOD-M-BLK', 'HOOD-M-GRY'] })
 const { h, page, ready, stock, capture } = journey, shop = ready.url
 const put = async (sku, name, unitCents, details, description = '') => { const draft = await h.command('product.prepare', { sku, name, description, unitCents, active: true, details }); return h.command('product.approve', { sku, revision: draft.revision }) }
 const material = value => ({ name: 'Material', value })
 await put('TSH-1', 'Linen t-shirt', 2500, { handle: 'linen-t-shirt', categories: ['Tops'], tags: ['summer'], attributes: [material('Cotton')] }, 'Light summer top')
 await put('HAT-1', 'Wool beanie', 1800, { categories: ['Accessories'], attributes: [material('Wool')] })
 await put('MUG-1', 'Ceramic mug', 2200, { categories: ['Home'], attributes: [material('Ceramic')] })
 await put('BAG-1', 'Cotton tote bag', 3000, { categories: ['Accessories'], attributes: [material('Cotton')] })
 await put('HOODIE', 'Fleece hoodie', 5000, { categories: ['Tops'], attributes: [material('Cotton')], options: [{ name: 'Size', values: ['S', 'M'] }, { name: 'Color', values: ['Black', 'Grey'] }], variants: [{ sku: 'HOOD-S-BLK', options: { Size: 'S', Color: 'Black' } }, { sku: 'HOOD-M-BLK', options: { Size: 'M', Color: 'Black' }, unitCents: 5500 }, { sku: 'HOOD-M-GRY', options: { Size: 'M', Color: 'Grey' }, unitCents: 5500 }] })
 const until = async (check, what) => { for (let i = 0; i < 100; i++) { if (await check()) return; await new Promise(resolve => setTimeout(resolve, 100)) } assert.fail(what) }
 const saved = (pick, what) => until(async () => pick((await h.api('/api/stall/state')).merchandising), what)
 const names = () => page.locator('.st-product h3').allInnerTexts()
 const count = () => page.locator('.st-result-count')
 // The desk: a hand-picked collection, a rule-based collection, a menu, a synonym and a pin.
 await page.getByRole('link', { name: 'Collections & search', exact: true }).click()
 await page.getByRole('heading', { name: 'Collections and search', level: 1 }).waitFor()
 await page.getByRole('button', { name: 'New collection', exact: true }).click()
 await page.getByLabel('Collection title', { exact: true }).fill('Gifts')
 await page.getByLabel('Collection handle', { exact: true }).fill('gifts')
 await page.getByLabel('Collection description', { exact: true }).fill('Small things people keep.')
 await page.getByLabel(/^Add a product/).selectOption({ label: 'Ceramic mug (MUG-1)' })
 await page.getByLabel(/^Add a product/).selectOption({ label: 'Wool beanie (HAT-1)' })
 await capture('STORE-002-collection-editor', page.getByRole('form', { name: 'New collection' }))
 await page.getByRole('button', { name: 'Save collection', exact: true }).click()
 await saved(value => value.collections.some(entry => entry.id === 'gifts'), 'the hand-picked collection saves')
 await page.getByRole('button', { name: 'New collection', exact: true }).click()
 await page.getByLabel('Collection title', { exact: true }).fill('Cotton goods')
 await page.getByLabel('Collection handle', { exact: true }).fill('cotton')
 await page.getByLabel(/^Collection type/).selectOption('rule')
 await page.getByLabel(/^Rule 1 field/).selectOption('attribute')
 await page.getByLabel('Rule 1 attribute name', { exact: true }).fill('Material')
 await page.getByLabel(/^Rule 1 value/).fill('Cotton')
 await page.getByRole('button', { name: 'Save collection', exact: true }).click()
 await saved(value => value.collections.some(entry => entry.id === 'cotton'), 'the rule-based collection saves')
 await page.getByRole('button', { name: 'Menus', exact: true }).click()
 await page.getByRole('button', { name: 'Add a menu item', exact: true }).click()
 await page.getByLabel('Item 1 label', { exact: true }).fill('Gifts')
 await page.getByLabel(/^Item 1 goes to/).selectOption('collection')
 await page.getByLabel(/^Item 1 destination/).selectOption({ label: 'Gifts' })
 await page.getByRole('button', { name: 'Save main menu', exact: true }).click()
 await saved(value => value.config.value.menus.main.length === 1, 'the menu saves')
 // Shoppers: the menu leads to the collection landing page.
 await page.goto(shop + '/shop')
 await page.getByRole('navigation', { name: 'Shop menu' }).getByRole('link', { name: 'Gifts', exact: true }).click()
 await page.getByRole('heading', { name: 'Gifts', level: 1 }).waitFor()
 await page.getByText('Small things people keep.', { exact: true }).waitFor()
 assert.deepEqual(await names(), ['Ceramic mug', 'Wool beanie'], 'a hand-picked collection keeps its order')
 assert.equal((await count().innerText()).trim(), '2 products')
 await capture('STORE-002-collection', page.locator('main'))
 // Filters combine and the address saves the view.
 await page.getByLabel(/^Accessories/).check()
 await page.waitForURL(url => url.search.includes('category=Accessories') && url.search.includes('collection=gifts'))
 await page.getByText('1 product', { exact: true }).waitFor()
 assert.deepEqual(await names(), ['Wool beanie'])
 const saved1 = page.url()
 await page.goto(saved1)
 await page.getByText('1 product', { exact: true }).waitFor()
 assert.equal(page.url(), saved1)
 await page.getByRole('button', { name: /^Clear all filters/ }).click()
 await page.getByRole('radio', { name: /^All products/ }).check()
 await page.getByText('5 products', { exact: true }).waitFor()
 await page.getByRole('radio', { name: /^Cotton goods/ }).check()
 await page.getByText('3 products', { exact: true }).waitFor()
 await page.getByLabel(/^M \(/).check()
 await page.getByText('1 product', { exact: true }).waitFor()
 assert.deepEqual(await names(), ['Fleece hoodie'])
 await capture('STORE-002-filters', page.locator('.st-browse'))
 // Search: no results before the synonym and the pin, useful results after.
 const search = async text => { await page.getByLabel('Search the shop').fill(text); await page.getByLabel('Search the shop').press('Enter') }
 await page.goto(shop + '/shop')
 await page.getByLabel('Search the shop').fill('lin')
 await page.getByRole('option', { name: /Linen t-shirt/ }).waitFor()
 await page.getByLabel('Search the shop').press('Enter')
 await page.getByText('1 product for “lin”', { exact: true }).waitFor()
 await search('tee')
 await page.getByRole('heading', { name: 'Nothing matches “tee”' }).waitFor()
 await page.goto(shop + '/app#shopfront')
 await page.getByRole('button', { name: 'Search', exact: true }).click()
 await page.getByLabel('Synonym groups', { exact: true }).fill('tee, t-shirt')
 await page.getByRole('button', { name: 'Save synonyms', exact: true }).click()
 await saved(value => value.config.value.synonyms.length === 1, 'the synonym saves')
 await page.goto(shop + '/shop?q=tee')
 await page.getByText('1 product for “tee”', { exact: true }).waitFor()
 assert.deepEqual(await names(), ['Linen t-shirt'])
 await page.goto(shop + '/shop?q=cotton')
 await page.getByText('3 products for “cotton”', { exact: true }).waitFor()
 const before = await names()
 assert.notEqual(before[0], 'Wool beanie')
 await page.goto(shop + '/app#shopfront')
 await page.getByRole('button', { name: 'Search', exact: true }).click()
 await page.getByRole('button', { name: 'Add a pinned search', exact: true }).click()
 await page.getByLabel('Search 1 query', { exact: true }).fill('cotton')
 await page.getByLabel('Search 1 pinned SKUs', { exact: true }).fill('HAT-1')
 await page.getByRole('button', { name: 'Save pinned products', exact: true }).click()
 await saved(value => value.config.value.pins.length === 1, 'the pin saves')
 await page.goto(shop + '/shop?q=cotton')
 await page.getByText('4 products for “cotton”', { exact: true }).waitFor()
 assert.equal((await names())[0], 'Wool beanie', 'a pinned product leads its query')
 await capture('STORE-002-pinned', page.locator('main'))
 await search('zzzz')
 await page.getByRole('heading', { name: 'Nothing matches “zzzz”' }).waitFor()
 await page.getByRole('link', { name: 'Gifts', exact: true }).first().waitFor()
 await capture('STORE-002-no-results', page.locator('main'))
 // The search report lists the empty search for the merchant.
 await page.goto(shop + '/app#shopfront')
 await page.getByRole('button', { name: 'Search', exact: true }).click()
 await page.getByRole('table', { name: 'Searches with no results' }).getByText('zzzz', { exact: true }).waitFor()
 await capture('STORE-002-search-report', page.getByRole('region', { name: 'Search report' }))
 // Publication and stock changes reach the results; the phone filters the same data.
 stock.setAvailable('HAT-1', '0')
 const mug = (await h.api('/api/stall/state')).products.find(product => product.id === 'MUG-1')
 const withdrawn = await h.command('product.prepare', { sku: 'MUG-1', revision: mug.revision, name: 'Ceramic mug', description: '', unitCents: 2200, active: false, details: mug.value.details })
 await h.command('product.approve', { sku: 'MUG-1', revision: withdrawn.revision })
 await page.goto(shop + '/shop?collection=gifts')
 await page.getByText('1 product', { exact: true }).waitFor()
 assert.deepEqual(await names(), ['Wool beanie'])
 await page.getByText('Sold out', { exact: true }).first().waitFor()
 await page.getByLabel(/^In stock only/).check()
 await page.getByRole('heading', { name: 'No products match these filters' }).waitFor()
 await page.setViewportSize({ width: 390, height: 900 })
 await page.goto(shop + '/shop')
 await page.getByText('Filters', { exact: true }).click()
 await page.getByLabel(/^Tops/).check()
 await page.getByText('2 products', { exact: true }).waitFor()
 assert.deepEqual((await names()).sort(), ['Fleece hoodie', 'Linen t-shirt'])
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'the phone view has no sideways scroll')
 await page.setViewportSize({ width: 1440, height: 1000 })
 const sitePage = await journey.context.newPage()
 for (const [path, label] of [['/docs/products', 'guide'], ['/contract', 'contract']]) { assert.equal((await sitePage.goto(ready.siteUrl + path)).status(), 200); await capture(`STORE-002-${label}`, sitePage.locator('body'), sitePage) }
 await sitePage.close()
 assert.deepEqual(journey.errors, [])
 await journey.dev.assertRunning()
 console.log('STORE-002 discovery journey passed: collections, menu, synonym, pin, filters, saved URLs, no-results state, search report, stock and publication changes at desktop and phone width')
} catch (error) { journeyError = error; throw error }
finally { await journey?.finish(journeyError) }
