import assert from 'node:assert/strict'
export async function workflowJourney({page,h,origin,assignee,capture,setActor}) {
 await page.goto(origin+'/app#settings')
 const form=page.getByRole('form',{name:'New workflow rule',exact:true})
 await form.getByLabel('Rule name',{exact:true}).fill('Replenish ceramic mugs')
 await form.getByLabel('Responsible staff',{exact:true}).selectOption(assignee.id)
 await form.getByLabel('Due after matching (minutes)',{exact:true}).fill('60')
 await form.getByLabel('Item SKU condition (optional)',{exact:true}).fill('MUG-BLUE')
 await form.getByLabel('Stock at most',{exact:true}).fill('25')
 await capture('workflow-editor',form)
 let response=page.waitForResponse(r=>r.url().endsWith('/api/stall/workflows')&&r.request().method()==='POST')
 await form.getByRole('button',{name:'Dry-run rule',exact:true}).click();assert.ok((await response).ok())
 await page.getByText('Dry-run explanation',{exact:true}).click();await capture('workflow-dry-run',page.locator('#workflows'))
 response=page.waitForResponse(r=>r.url().endsWith('/api/stall/workflows')&&r.request().method()==='POST')
 await form.getByRole('button',{name:'Save workflow draft',exact:true}).click();assert.ok((await response).ok())
 const rule=page.getByRole('article',{name:'Workflow Replenish ceramic mugs',exact:true})
 await rule.getByRole('button',{name:'Activate rule',exact:true}).waitFor()
 response=page.waitForResponse(r=>r.url().endsWith('/api/stall/workflows')&&r.request().method()==='POST')
 await rule.getByRole('button',{name:'Activate rule',exact:true}).click();assert.ok((await response).ok())
 response=page.waitForResponse(r=>r.url().endsWith('/api/stall/workflows')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'Run active workflows now',exact:true}).click();assert.ok((await response).ok())
 await page.getByRole('button',{name:'Mark task complete',exact:true}).first().waitFor()
 const before=await h.api('/api/stall/workflows');assert.equal(before.tasks.length,1);assert.equal(before.tasks[0].assigneeId,assignee.id)
 assert.equal(Date.parse(before.tasks[0].dueAt)-Date.parse(before.tasks[0].createdAt),3600000)
 await capture('workflow-task',page.getByRole('article',{name:`Task ${before.tasks[0].id}`,exact:true}))
 await h.api('/api/stall/workflows',{type:'workflow.run',payload:{}})
 assert.equal((await h.api('/api/stall/workflows')).tasks.length,1)
 // A rule with quiet-hour work can be paused before an alert is dispatched.
 const zone=before.timeZone,parts=new Intl.DateTimeFormat('en-US',{timeZone:zone,hour:'2-digit',minute:'2-digit',hourCycle:'h23'}).formatToParts(new Date()),values=Object.fromEntries(parts.map(p=>[p.type,p.value]))
 const minute=Number(values.hour)*60+Number(values.minute),clock=m=>`${String(Math.floor((m+1440)%1440/60)).padStart(2,'0')}:${String((m+1440)%60).padStart(2,'0')}`
 const saved=(await h.api('/api/stall/workflows',{type:'workflow.save',payload:{rule:{name:'Quiet-hour stock check',trigger:'low_stock',assigneeId:assignee.id,dueMinutes:120,conditions:{sku:'MUG-BLUE',stockAtMost:25},quietHours:{start:clock(minute-60),end:clock(minute+60)}}}})).result
 await h.api('/api/stall/workflows',{type:'workflow.activate',payload:{id:saved.id,revision:saved.revision}});await h.api('/api/stall/workflows',{type:'workflow.run',payload:{}})
 await page.reload();const quiet=page.getByRole('article',{name:'Workflow Quiet-hour stock check',exact:true})
 await quiet.getByRole('button',{name:'Pause rule',exact:true}).waitFor()
 response=page.waitForResponse(r=>r.url().endsWith('/api/stall/workflows')&&r.request().method()==='POST')
 await quiet.getByRole('button',{name:'Pause rule',exact:true}).click();assert.ok((await response).ok())
 const pending=(await h.api('/api/stall/workflows')).tasks.find(t=>t.ruleId===saved.id);assert.equal(pending.status,'paused')
 await capture('workflow-paused',page.getByRole('article',{name:`Task ${pending.id}`,exact:true}))
 setActor(assignee.cookie);await page.reload()
 await page.getByRole('heading',{name:'Your staff account',exact:true}).waitFor()
 assert.equal(await page.getByRole('form',{name:'New workflow rule',exact:true}).count(),0)
 const task=page.getByRole('article',{name:`Task ${before.tasks[0].id}`,exact:true})
 await task.getByRole('button',{name:'Mark task complete',exact:true}).waitFor();await capture('workflow-staff-inbox',page.locator('#workflows'))
 response=page.waitForResponse(r=>r.url().endsWith('/api/stall/workflows')&&r.request().method()==='POST')
 await task.getByRole('button',{name:'Mark task complete',exact:true}).click();assert.ok((await response).ok());await task.getByText('completed',{exact:true}).waitFor()
 await capture('workflow-completed',task)
 setActor(h.cookie)
}
