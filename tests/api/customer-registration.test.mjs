import test from 'node:test'
import assert from 'node:assert/strict'
import { installation } from './harness.mjs'

const intake='/api/stall/customer/registration'
const reviews='/api/stall/customer/registration-requests'
const details=(n)=>({email:`synthetic-stall-${n}@example.test`,displayName:`Synthetic Stall ${n}`,necessaryAccountConsent:true})

test('public account requests require an owner decision and the real native email confirmation before access',async()=>{
 const h=await installation()
 try {
  const customer=details(1),mailBefore=h.messages.length
  await h.api(intake,{...customer,necessaryAccountConsent:false},{as:'',status:400})
  await h.api(intake,customer,{as:'',headers:{origin:'https://foreign.example.test'},status:403})
  await h.api(intake,customer,{as:'',headers:{origin:''},status:403})
  await h.api(intake,customer,{as:'',headers:{'sec-fetch-site':'cross-site'},status:403})
  const answer=await h.api(intake,customer,{as:'',status:202})
  await h.api('/api/stall/account',undefined,{as:'',status:401})
  assert.equal(await h.db.prepare('SELECT id FROM oa_operators WHERE email=?').bind(customer.email).first(),null)
  assert.equal(h.messages.length,mailBefore)
  const pending=(await h.api(reviews)).requests.find(row=>row.email===customer.email)
  assert.ok(pending)
  assert.deepEqual(await h.api(intake,{...customer,displayName:'A changed unverified name'},{as:'',status:202}),answer)
  assert.deepEqual((await h.api(reviews)).requests.find(row=>row.email===customer.email),pending)
  await h.api(reviews,undefined,{as:'',status:401})
  await h.api(reviews,undefined,{headers:{origin:'https://foreign.example.test'},status:403})
  await h.api(reviews,undefined,{headers:{'sec-fetch-site':'cross-site'},status:403})
  const {token}=await h.api('/api/stall/agent-token',{})
  await h.api(reviews,undefined,{as:'',headers:{authorization:'Bearer '+token},status:403})
  await h.api(intake,customer,{as:'',headers:{authorization:'Bearer '+token},status:403})
  const decision={id:pending.id,decision:'approve',reviewed:true}
  await h.api(reviews,decision,{as:'',headers:{authorization:'Bearer '+token},status:403})
  await h.api(reviews,decision,{headers:{origin:'https://foreign.example.test'},status:403})
  await h.api(reviews,{...decision,reviewed:false},{status:400})
  assert.equal(h.messages.length,mailBefore)

  await h.api(reviews,decision)
  assert.equal(h.messages.length,mailBefore+1)
  assert.equal((await h.db.prepare('SELECT status FROM oa_operators WHERE email=?').bind(customer.email).first()).status,'invited')
  await h.api('/auth/magic-link',{email:customer.email,returnTo:'/order'},{as:'',status:202})
  assert.equal(h.messages.length,mailBefore+1)
  await h.api('/api/stall/account',undefined,{as:'',status:401})
  await h.api(reviews,decision,{status:409})
  assert.equal(h.messages.length,mailBefore+1)
  const message=h.messages.at(-1)
  assert.ok(JSON.stringify(message.to).includes(customer.email))
  const link=new URL(message.text.match(/https?:\/\/[^\s<>]+\/auth\/confirm\?token=[^\s<>]+/)[0])
  const preview=await h.request(link.pathname+link.search,{as:''})
  assert.equal(preview.status,200)
  assert.equal(preview.headers.getSetCookie().length,0)
  assert.equal((await h.db.prepare('SELECT status FROM oa_operators WHERE email=?').bind(customer.email).first()).status,'invited')
  const confirmed=await h.request('/auth/confirm',{method:'POST',as:'',body:{token:link.searchParams.get('token')}})
  assert.equal(confirmed.status,303)
  assert.equal(confirmed.headers.get('location'),'/order')
  const cookie=confirmed.headers.getSetCookie().map(value=>value.split(';')[0]).join('; ')
  assert.equal((await h.api('/api/stall/account',undefined,{as:cookie})).email,customer.email)
  await h.api(reviews,undefined,{as:cookie,status:403})
  await h.api(reviews,decision,{as:cookie,status:403})
  await h.api('/auth/confirm',{token:link.searchParams.get('token')},{as:'',status:400})
  const identity=await h.db.prepare('SELECT * FROM oa_operators WHERE email=?').bind(customer.email).first()
  assert.deepEqual(await h.api(intake,{...customer,displayName:'Untrusted replacement'},{as:'',status:202}),answer)
  assert.deepEqual(await h.db.prepare('SELECT * FROM oa_operators WHERE email=?').bind(customer.email).first(),identity)
  assert.equal(h.messages.length,mailBefore+1)
  const decided=await h.db.prepare('SELECT requested_at,decided_at,decided_by,email,display_name FROM st_customer_registrations WHERE id=?').bind(pending.id).first()
  assert.ok(decided.requested_at<=decided.decided_at)
  assert.ok(decided.decided_by)
  assert.equal(decided.email,null)
  assert.equal(decided.display_name,null)
  assert.ok(await h.db.prepare('SELECT id FROM st_audit WHERE subject=? AND actor=?').bind(pending.id,decided.decided_by).first())

  const expired=details(2),expiredHeaders={'CF-Connecting-IP':'192.0.2.2'}
  await h.api(intake,expired,{as:'',headers:expiredHeaders,status:202})
  const previous=(await h.api(reviews)).requests.find(row=>row.email===expired.email)
  await h.db.prepare('UPDATE st_customer_registrations SET expires_at=? WHERE id=?').bind(Date.now()-1,previous.id).run()
  await h.api(reviews,{id:previous.id,decision:'approve',reviewed:true},{status:409})
  assert.equal(await h.db.prepare('SELECT id FROM oa_operators WHERE email=?').bind(expired.email).first(),null)
  const scrubbed=await h.db.prepare('SELECT email,display_name,email_key FROM st_customer_registrations WHERE id=?').bind(previous.id).first()
  assert.deepEqual(scrubbed,{email:null,display_name:null,email_key:null})
  await h.api(intake,expired,{as:'',headers:expiredHeaders,status:202})
  const renewed=(await h.api(reviews)).requests.find(row=>row.email===expired.email)
  assert.notEqual(renewed.id,previous.id)
  await h.api(reviews,{id:renewed.id,decision:'decline',reviewed:true})
  await h.api(intake,expired,{as:'',headers:expiredHeaders,status:202})
  assert.ok(!(await h.api(reviews)).requests.some(row=>row.email===expired.email))
  assert.equal(h.messages.length,mailBefore+1)

  const administrator=await h.signIn(details(3).email,'admin')
  await h.api(reviews,undefined,{as:administrator,status:403})
  const burst=Array.from({length:24},(_,i)=>details(i+10))
  const replies=await Promise.all(burst.map(body=>h.api(intake,body,{as:'',headers:{'CF-Connecting-IP':'192.0.2.3'},status:202})))
  replies.forEach(reply=>assert.deepEqual(reply,answer))
  const queued=(await h.api(reviews)).requests.filter(row=>burst.some(body=>body.email===row.email))
  assert.ok(queued.length>0&&queued.length<burst.length)
  assert.equal(h.messages.length,mailBefore+2)
 }finally{await h.close()}
})
